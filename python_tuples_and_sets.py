# Create a set using curly braces
stud_info = {101, "Manish", "CSE", 21, 8.5}

# Remove an item (works perfectly)
stud_info.remove(21)
print(stud_info)

# WARNING: .remove(102) will cause a KeyError because 102 is not in the set.
# Use .discard(102) instead if you want to avoid errors when an item is missing.
stud_info.discard(102)
print(stud_info)

# Discard an item (works without errors)
