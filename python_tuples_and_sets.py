"""# SET Operations
## 1. Union
## 2. Intersection
## 3. Difference
## 4.Complement
## 5.Subset,superset,disjoint
"""

# Create two sets
python_students = {"Rahul", "Vani", "Manish", "Anil", "Chirag"}
java_students = {"Manish", "Lalith", "Anil", "Ranjith", "Sanjiv"}

# 1. Union operation
result = python_students.union(java_students)
print("Union Operations:", result)

# 2. Intersection operation
result_inter = python_students.intersection(java_students)
print("Result of Intersection operation:", result_inter)

# 3. Difference operation (इसका रिजल्ट अब प्रिंट होगा)
result_diff = python_students.difference(java_students)
print("Result of Difference operation:", result_diff)

